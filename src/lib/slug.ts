/**
 * สร้าง slug สำหรับ URL ของงาน
 *
 * เก็บอักษรไทยไว้ตามเดิม ไม่ถอดเป็นอักษรโรมัน เพราะ:
 *  1. URL รองรับ UTF-8 อยู่แล้ว และ Google อ่าน URL ภาษาไทยได้ปกติ
 *  2. คนไทยที่เห็น URL จะรู้ทันทีว่าเป็นงานอะไร ซึ่งช่วยให้กล้าคลิกตอนแชร์ผ่าน LINE
 *  3. การถอดเสียงไทยเป็นอังกฤษไม่มีมาตรฐานเดียว ทำแล้วได้ผลไม่แน่นอน
 *
 * ต่อท้ายด้วยรหัสสั้นจากเวลาปัจจุบันเสมอ เพื่อกันชนกับงานชื่อซ้ำ
 * (คอลัมน์ slug ในฐานข้อมูลเป็น unique — ถ้าชนจะ insert ไม่ผ่าน)
 */
export function createEventSlug(title: string): string {
  const base = title
    .toLowerCase()
    .trim()
    // ตัดอักขระที่ไม่ใช่อักษรไทย ตัวเลข อักษรอังกฤษ หรือช่องว่าง
    .replace(/[^฀-๿a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);

  const suffix = Date.now().toString(36).slice(-5);

  // ชื่อที่มีแต่อักขระพิเศษอาจเหลือว่าง จึงต้องมีค่าสำรอง
  return base ? `${base}-${suffix}` : `event-${suffix}`;
}

/**
 * แปลงค่า [slug] ที่ได้จาก URL ให้กลับเป็นข้อความเดิมก่อนนำไปค้นในฐานข้อมูล
 *
 * ⚠️ จำเป็นเพราะ slug ของเราเป็นภาษาไทย
 * เบราว์เซอร์ส่ง URL ภาษาไทยมาในรูปแบบ percent-encoded (`%E0%B8%87...`)
 * และค่าที่ Next ส่งเข้า params ยังเป็นรูปแบบนั้นอยู่ ไม่ได้ถอดรหัสให้
 * ถ้าเอาไปเทียบกับคอลัมน์ slug ตรงๆ จะไม่มีทางตรง ทำให้ทุกงานที่ชื่อเป็นภาษาไทย
 * เปิดหน้ารายละเอียดไม่ได้เลย (ขึ้น 404 ทั้งที่ข้อมูลอยู่ในฐานข้อมูลครบ)
 *
 * slug ที่เป็นอักษรอังกฤษล้วนไม่มีอะไรให้ถอด ฟังก์ชันนี้จึงคืนค่าเดิม —
 * เรียกซ้ำกี่ครั้งก็ได้ผลเท่าเดิม (createEventSlug ตัด `%` ทิ้งอยู่แล้ว)
 */
export function readEventSlugParam(raw: string): string {
  try {
    return decodeURIComponent(raw);
  } catch {
    // URL ที่ encode มาผิดรูป (เช่น `%zz`) — ใช้ค่าดิบต่อไป แล้วปล่อยให้หาไม่เจอตามปกติ
    return raw;
  }
}
