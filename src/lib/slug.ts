/**
 * สร้าง slug สำหรับ URL ของงาน
 *
 * เก็บอักษรไทยไว้ตามเดิม ไม่ถอดเป็นอักษรโรมัน เพราะ:
 *  1. URL รองรับ UTF-8 อยู่แล้ว และ Google อ่าน URL ภาษาไทยได้ปกติ
 *  2. คนไทยที่เห็น URL จะรู้ทันทีว่าเป็นงานอะไร ซึ่งช่วยให้กล้าคลิกตอนแชร์ผ่าน LINE
 *  3. การถอดเสียงไทยเป็นอังกฤษไม่มีมาตรฐานเดียว ทำแล้วได้ผลไม่แน่นอน
 *
 * ต่อท้ายด้วยรหัสสั้นจากเวลาปัจจุบันเสมอ เพื่อกันชนกับงานชื่อซ้ำ
 * (คอลัมน์ slug ในฐานข้อมูลเป็น unique — ถ้าชนจะ insert ไม่ผ่าน)
 */
export function createEventSlug(title: string): string {
  const base = title
    .toLowerCase()
    .trim()
    // ตัดอักขระที่ไม่ใช่อักษรไทย ตัวเลข อักษรอังกฤษ หรือช่องว่าง
    .replace(/[^฀-๿a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);

  const suffix = Date.now().toString(36).slice(-5);

  // ชื่อที่มีแต่อักขระพิเศษอาจเหลือว่าง จึงต้องมีค่าสำรอง
  return base ? `${base}-${suffix}` : `event-${suffix}`;
}
