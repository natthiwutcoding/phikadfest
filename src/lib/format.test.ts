import { describe, expect, it } from "vitest";

import {
  bangkokDay,
  bangkokTime,
  formatAddress,
  formatDateRange,
  formatDayRange,
  formatDistance,
  formatPrice,
  formatRelativeDay,
  formatTimeRange,
} from "@/lib/format";

/**
 * เทสต์ชุดนี้รันด้วย TZ=UTC (ตั้งไว้ใน vitest.config.ts) โดยจงใจ
 *
 * เพราะเหตุผลที่ไฟล์ lib/format.ts มีอยู่คือการตรึงเขตเวลาไทยไม่ให้ขึ้นกับเครื่องที่รัน
 * ถ้าเทสต์รันด้วยเวลาไทย มันจะผ่านทั้งที่โค้ดใช้เวลาท้องถิ่น — ซึ่งเป็นบั๊กที่จะไปโผล่
 * ตอน deploy ขึ้น Vercel (รัน UTC) ไม่ใช่ตอนพัฒนา
 */

describe("bangkokDay", () => {
  it("นับวันตามเวลาไทย ไม่ใช่ UTC", () => {
    // 21 ส.ค. 18:00 UTC = 22 ส.ค. 01:00 ที่ไทย — ถ้าใช้ toISOString() จะได้ 2026-08-21 ซึ่งผิด
    expect(bangkokDay("2026-08-21T18:00:00Z")).toBe("2026-08-22");
  });

  it("ก่อนเที่ยงคืนเวลาไทยยังเป็นวันเดิม", () => {
    // 21 ส.ค. 16:59 UTC = 21 ส.ค. 23:59 ที่ไทย
    expect(bangkokDay("2026-08-21T16:59:00Z")).toBe("2026-08-21");
  });
});

describe("bangkokTime", () => {
  it("แปลงเวลาเป็นเขตเวลาไทย ไม่ใช่เวลาของเครื่องที่รัน", () => {
    // 11:00 UTC = 18:00 ที่ไทย
    expect(bangkokTime("2026-11-14T11:00:00Z")).toBe("18:00");
  });

  it("คืนรูปแบบ HH:MM ที่ <input type='time'> รับได้ตรงๆ", () => {
    expect(bangkokTime("2026-11-14T02:05:00+07:00")).toBe("02:05");
  });
});

describe("formatDateRange", () => {
  it("งานวันเดียวแสดงชื่อวันด้วย", () => {
    expect(formatDateRange("2026-08-22T10:00:00+07:00", "2026-08-22T22:00:00+07:00")).toBe(
      "ส. 22 ส.ค. 2569",
    );
  });

  it("งานข้ามวันในเดือนเดียวกันไม่เขียนเดือนซ้ำ", () => {
    expect(formatDateRange("2026-08-22T10:00:00+07:00", "2026-08-24T22:00:00+07:00")).toBe(
      "22 – 24 ส.ค. 2569",
    );
  });

  it("งานข้ามเดือนเขียนเดือนทั้งสองฝั่ง", () => {
    expect(formatDateRange("2026-08-30T10:00:00+07:00", "2026-09-02T22:00:00+07:00")).toBe(
      "30 ส.ค. – 2 ก.ย. 2569",
    );
  });

  it("งานที่เริ่มดึกตามเวลาไทยยังนับเป็นวันที่ถูกต้อง", () => {
    // เริ่ม 23:00 ของวันที่ 22 ตามเวลาไทย = 16:00 UTC — ถ้าเผลอใช้ UTC จะเพี้ยนเป็นวันที่ 22 ตอน 16:00
    expect(formatDateRange("2026-08-22T23:00:00+07:00", "2026-08-23T02:00:00+07:00")).toBe(
      "22 – 23 ส.ค. 2569",
    );
  });
});

describe("formatTimeRange", () => {
  it("งานไม่ระบุเวลาไม่ต้องแสดงช่วงเวลา", () => {
    expect(formatTimeRange("2026-08-22T00:00:00+07:00", "2026-08-22T23:59:59+07:00", true)).toBeNull();
  });

  it("งานวันเดียวแสดงเวลาเริ่มถึงเวลาจบ", () => {
    expect(formatTimeRange("2026-08-22T18:00:00+07:00", "2026-08-22T23:00:00+07:00", false)).toBe(
      "18:00 – 23:00 น.",
    );
  });

  it("งานข้ามวันบอกแค่เวลาเริ่ม เพราะเวลาจบคนละวันสื่อสารสับสน", () => {
    expect(formatTimeRange("2026-08-22T18:00:00+07:00", "2026-08-24T23:00:00+07:00", false)).toBe(
      "เริ่ม 18:00 น.",
    );
  });
});

describe("formatRelativeDay", () => {
  const now = new Date("2026-09-03T05:00:00+07:00");

  it("งานหลายวันที่เริ่มไปแล้วแต่ยังไม่จบ", () => {
    expect(
      formatRelativeDay("2026-09-01T10:00:00+07:00", "2026-09-05T22:00:00+07:00", now),
    ).toBe("กำลังจัดอยู่");
  });

  it("งานหลายวันที่เริ่มวันนี้ยังไม่ใช่ 'กำลังจัดอยู่'", () => {
    // เปิดหน้าตอนตี 5 แล้วเห็นว่างานที่เริ่มบ่ายนี้ 'กำลังจัดอยู่' คือการบอกข้อมูลผิด
    expect(
      formatRelativeDay("2026-09-03T14:00:00+07:00", "2026-09-06T22:00:00+07:00", now),
    ).toBe("วันนี้");
  });

  it("งานวันนี้", () => {
    expect(
      formatRelativeDay("2026-09-03T18:00:00+07:00", "2026-09-03T23:00:00+07:00", now),
    ).toBe("วันนี้");
  });

  it("งานพรุ่งนี้", () => {
    expect(
      formatRelativeDay("2026-09-04T18:00:00+07:00", "2026-09-04T23:00:00+07:00", now),
    ).toBe("พรุ่งนี้");
  });

  it("งานอีกไม่กี่วัน", () => {
    expect(
      formatRelativeDay("2026-09-08T18:00:00+07:00", "2026-09-08T23:00:00+07:00", now),
    ).toBe("อีก 5 วัน");
  });

  it("งานไกลเกิน 30 วันไม่ต้องมีป้าย", () => {
    expect(
      formatRelativeDay("2026-11-01T18:00:00+07:00", "2026-11-01T23:00:00+07:00", now),
    ).toBeNull();
  });

  it("งานที่จบไปแล้วไม่ต้องมีป้าย", () => {
    expect(
      formatRelativeDay("2026-08-01T18:00:00+07:00", "2026-08-02T23:00:00+07:00", now),
    ).toBeNull();
  });
});

describe("formatPrice", () => {
  it("งานเข้าฟรี", () => {
    expect(formatPrice(true)).toBe("เข้าฟรี");
  });

  it("ไม่รู้ราคาให้บอกตรงๆ แทนการเดา", () => {
    expect(formatPrice(false)).toBe("ตรวจสอบกับผู้จัด");
  });

  it("ราคาเดียว", () => {
    expect(formatPrice(false, 350)).toBe("350 บาท");
  });

  it("ช่วงราคาใส่จุลภาคคั่นหลักพัน", () => {
    expect(formatPrice(false, 350, 1200)).toBe("350 – 1,200 บาท");
  });

  it("ราคาต่ำสุดเท่าสูงสุดไม่ต้องแสดงเป็นช่วง", () => {
    expect(formatPrice(false, 500, 500)).toBe("500 บาท");
  });
});

describe("formatAddress", () => {
  it("เติมคำนำหน้าจังหวัดให้ที่อยู่", () => {
    expect(formatAddress("ต.บางแสน อ.เมือง", "ชลบุรี")).toBe("ต.บางแสน อ.เมือง จ.ชลบุรี");
  });

  it("ไม่เขียนจังหวัดซ้ำเมื่อผู้กรอกพิมพ์มาแล้ว", () => {
    expect(formatAddress("ต.บางแสน อ.เมือง ชลบุรี", "ชลบุรี")).toBe("ต.บางแสน อ.เมือง ชลบุรี");
  });

  it("กรุงเทพฯ ไม่ใช้คำนำหน้า จ.", () => {
    expect(formatAddress(undefined, "กรุงเทพมหานคร")).toBe("กรุงเทพมหานคร");
  });
});

describe("formatDistance", () => {
  it("ต่ำกว่าหนึ่งกิโลเมตรบอกเป็นเมตร", () => {
    expect(formatDistance(850)).toBe("850 ม.");
  });

  it("ต่ำกว่าสิบกิโลเมตรบอกทศนิยมหนึ่งตำแหน่ง", () => {
    expect(formatDistance(8_400)).toBe("8.4 กม.");
  });

  it("ไกลกว่านั้นปัดเป็นจำนวนเต็ม เพราะทศนิยมไม่ช่วยให้ตัดสินใจต่างไป", () => {
    expect(formatDistance(12_400)).toBe("12 กม.");
    expect(formatDistance(133_200)).toBe("133 กม.");
  });
});

describe("formatDayRange", () => {
  it("ไม่ได้เลือกวันเลย", () => {
    expect(formatDayRange()).toBeNull();
  });

  it("ระบุแค่วันเริ่ม", () => {
    expect(formatDayRange("2026-09-03")).toBe("ตั้งแต่ 3 ก.ย. 2569");
  });

  it("ระบุแค่วันสิ้นสุด", () => {
    expect(formatDayRange(undefined, "2026-09-10")).toBe("ถึง 10 ก.ย. 2569");
  });

  it("วันเดียว", () => {
    expect(formatDayRange("2026-09-03", "2026-09-03")).toBe("3 ก.ย. 2569");
  });

  it("ช่วงในเดือนเดียวกันไม่เขียนเดือนซ้ำ", () => {
    expect(formatDayRange("2026-09-03", "2026-09-10")).toBe("3 – 10 ก.ย. 2569");
  });

  it("ช่วงข้ามเดือนเขียนเดือนทั้งสองฝั่ง", () => {
    expect(formatDayRange("2026-08-30", "2026-09-02")).toBe("30 ส.ค. – 2 ก.ย. 2569");
  });
});
